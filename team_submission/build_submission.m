%BUILD_SUBMISSION  Combine all task models into ONE file for the graders.
%
%   run('team_submission/build_submission.m')
%
% Writes team_submission/SUBMIT/pm2d5_pred_model.m: the dispatcher
% (pm2d5_pred_model.m) followed by every task-model file as local functions:
%   every other .m in team_submission/ (pm_short_term.m, pm_long_term.m,
%   pm_interpolation.m, pm_draft_level_model.m, and any helper files added)
% To avoid name clashes, each file's HELPER functions are renamed
% <filename>__<helper> inside that file's text. The main function of each file
% keeps its name, so files call each other as usual.
% Rules for files: functions only (no scripts), every function ends with
% "end", no load / clear / figures / absolute paths inside the model.
% Then run team_submission/check_submission.m to test the built file.

here = fileparts(mfilename('fullpath'));
if isempty(here), here = fullfile(pwd, 'team_submission'); end
root = fileparts(here);
skip = {'pm2d5_pred_model.m', 'build_submission.m', 'check_submission.m'};
F = dir(fullfile(here, '*.m'));
files = {fullfile(here, 'pm2d5_pred_model.m')};
for i = 1:numel(F)
    if ~any(strcmp(F(i).name, skip)), files{end+1} = fullfile(here, F(i).name); end %#ok<SAGROW>
end

mains = {}; parts = {};
fnPat = '^\s*function\s+(?:\[[^\]]*\]\s*=\s*|[A-Za-z]\w*\s*=\s*)?([A-Za-z]\w*)';
for i = 1:numel(files)
    txt = fileread(files{i});
    k = strfind(txt, '%[appendix]');                   % Live Script export: drop saved outputs
    if ~isempty(k), txt = txt(1:k(1)-1); end
    lines = regexp(txt, '\r?\n', 'split');
    names = {};
    for L = 1:numel(lines)
        tok = regexp(lines{L}, fnPat, 'tokens', 'once');
        if ~isempty(tok), names{end+1} = tok{1}; end %#ok<SAGROW>
    end
    [~, base] = fileparts(files{i});
    if isempty(names) || ~strcmp(names{1}, base)
        error('build_submission: %s must be a function file whose first function is %s', files{i}, base);
    end
    mains{end+1} = base; %#ok<SAGROW>
    for h = 2:numel(names)                              % rename helpers of THIS file
        newName = [base '__' names{h}];
        if numel(newName) > 63, newName = [base(1:min(end,20)) '__' names{h}]; end
        txt = regexprep(txt, ['(?<![\w.])' names{h} '(?!\w)'], newName);
    end
    parts{end+1} = sprintf('%% ===== from %s =====\n%s', strrep(files{i}, [root filesep], ''), strtrim(txt)); %#ok<SAGROW>
    fprintf('  %-55s main: %-22s helpers renamed: %d\n', strrep(files{i}, [root filesep], ''), base, numel(names) - 1);
end
[u, ~, j] = unique(mains);
if numel(u) < numel(mains), error('build_submission: duplicate function file names: %s', strjoin(u(accumarray(j(:),1) > 1), ', ')); end

outDir = fullfile(here, 'SUBMIT'); if ~exist(outDir, 'dir'), mkdir(outDir); end
out = fullfile(outDir, 'pm2d5_pred_model.m');
fid = fopen(out, 'w');
fprintf(fid, '%s\n', parts{1});
fprintf(fid, '\n%% %s\n%% Everything below is generated by team_submission/build_submission.m from the\n%% task-model files listed in each "from" line. Edit those files, not this one.\n%% %s\n', repmat('=', 1, 75), repmat('=', 1, 75));
for i = 2:numel(parts), fprintf(fid, '\n%s\n', parts{i}); end
fclose(fid);
fprintf('\nWrote %s  (%d files, %d lines)\n', out, numel(files), numel(regexp(fileread(out), '\n')));
