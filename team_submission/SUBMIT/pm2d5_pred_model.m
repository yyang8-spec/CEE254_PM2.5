% ===== from short_term_pipeline/model/pm_short_term.m =====
function [pred, pred_sd, info] = pm_short_term(train_data, test_data, opts)
%PM_SHORT_TERM  Short-term (next 3 h) PM2.5 prediction - problem_type = 1.
%
%   pred = pm_short_term(train_data, test_data)
%   [pred, pred_sd, info] = pm_short_term(train_data, test_data, opts)
%
%   train_data  P x 7  [time, humidity, temperature, speed, pm2d5, lat, lon]
%               3 days of ALL devices (static + mobile, no device ID)
%   test_data   M x 6  [time, humidity, temperature, speed, lat, lon]
%               hourly rows for the next 3 h at one or more fixed test sites
%   opts        optional struct, only for tuning / ablations (see defaults)
%
%   pred        M x 1  predicted hourly PM2.5, same row order as test_data
%   pred_sd     M x 1  1-sigma predictive uncertainty (report section j)
%   info        diagnostics (number of sites, dropped sites, offsets, ...)
%
% MODEL
%   PM(site, t) = L(t) + o(site)
%     L(t)    city-wide PM2.5 level. The static sensors move together (hourly
%             correlation 0.93-0.98 in Foshan), so one shared level explains
%             most of the variance (spread between sites ~5 ug/m3 vs ~19 over
%             time).
%     o(site) the site's offset from the city level.
%   Forecast: L(t0 + h) = exponentially smoothed L at the forecast origin
%             (persistence), held flat for h = 1, 2, 3 h.
%
% WHY PERSISTENCE AND NOT REGRESSION (validated, see short_term/README.md)
%   * PM 1 h ago correlates 0.96 with PM now. Of the features tested, only
%     the most recent 1-h trend is moderately related to the 1-3 h CHANGE
%     (r = 0.44 / 0.33 / 0.25, city level); weather and hour of day are weak.
%   * Linear regression and ridge (lambda chosen on a chronological
%     validation split) beat persistence on validation but LOST on the
%     held-out test period, on all 5 sensors and with multi-sensor
%     features (including aligned trend terms): they overfit one 3-day
%     window, and momentum reverses sharply after pollution peaks.
%
% RESULTS (st_validate.m: leave-one-static-sensor-out, Foshan, forecasts
% every 3 h; tau chosen on the first half of the origins, then the model is
% scored once on the second half)
%   held-out TEST half, NRMSE     noise 0  /  0.5 sigma  /  1.0 sigma
%   ours (tau 2)                  0.2038   /  0.2052     /  0.2073
%   nearest-sensor last-hour mean 0.2332   /  0.2329     /  0.2327
%
% Plain MATLAB, no toolboxes; also runs in GNU Octave.

if nargin < 3 || isempty(opts), opts = struct(); end
opts = pm_short_term__fill_defaults(opts);
% The 11/16 competition files are MATLAB tables, not matrices: accept both.
train_data = pm_short_term__table_to_matrix(train_data, true);
test_data  = pm_short_term__table_to_matrix(test_data, false);

%% 1. PARSE ---------------------------------------------------------------
% The competition gives plain matrices. Two things are not guaranteed:
%  (a) time format: MATLAB datenum (days), POSIX seconds or milliseconds
%  (b) column order of temperature / speed: the course PDF says
%      [hmd tmp spd] but the Canvas tables are [hmd spd tmp].
% Both are detected from the data instead of assumed.
tr = pm_short_term__parse_matrix(train_data, true);
te = pm_short_term__parse_matrix(test_data, false);

%% 2. CLEAN ---------------------------------------------------------------
% Remove only what is clearly wrong. Every step is logged in info.clean.
n0 = numel(tr.t);
% 2a. rows without time / PM / position cannot be used
ok = isfinite(tr.t) & isfinite(tr.pm) & isfinite(tr.lat) & isfinite(tr.lon);
info.clean.missing = sum(~ok);
% 2b. GPS errors: (0,0) fixes or points far (> 0.5 deg ~ 50 km) from the bulk
%     of the data. None in the Canvas files, kept for the competition data.
mlat = pm_short_term__medn(tr.lat(ok)); mlon = pm_short_term__medn(tr.lon(ok));
gps = (tr.lat == 0 & tr.lon == 0) | abs(tr.lat - mlat) > 0.5 | abs(tr.lon - mlon) > 0.5;
info.clean.gps = sum(ok & gps); ok = ok & ~gps;
% 2c. gross spikes: PM > median + k * robust sd (MAD-based, so the
%     threshold itself is not inflated by the spikes). Mobile sensors spike
%     to 1494 in Foshan; this removes 2,962 rows (0.14%, all mobile).
%     NOTE: we never clip negative values. The robustness test adds
%     zero-mean Gaussian noise to every 3-s sample; clipping the resulting
%     negatives would bias every bin mean upward.
p = tr.pm(ok); med = median(p); s = 1.4826 * median(abs(p - med));
spike = tr.pm > med + opts.spike_k * max(s, 1);
info.clean.spikes = sum(ok & spike); ok = ok & ~spike;
tr = pm_short_term__subset(tr, ok);
info.clean.kept = sprintf('%d of %d rows', numel(tr.t), n0);

%% 3. SEPARATE STATIC FROM MOBILE ------------------------------------------
% There is no device ID. A static sensor logs ~1200 samples/h at ONE exact
% coordinate. A coordinate is a static site if ALL of:
%   * it has data in >= 50% of the hours of the window (static sensors run
%     24 h; mobile sensors are off at night),
%   * its median speed is < 2,
%   * it has >= 5% of the samples of the busiest coordinate.
% The last rule fixes a real bug: Foshan mobile #2 parks at a depot, and its
% GPS jitter spreads it over ~70 coordinates with ~300 samples each and
% >50% hourly coverage. Those passed as "static sites" and outvoted the 4
% real ones. Ablation (st_validate.m, held-out test half) without this rule:
% NRMSE 0.2479 / 0.7613 / 0.7698 at noise 0 / 0.5 / 1.0 sigma, vs 0.2038 /
% 0.2052 / 0.2073 with it.
% (5%, not more: co-located sensors - Tianjin static 1/3/4 - triple the
% count of their shared coordinate.)
th = floor(tr.t * 24); nHours = max(th) - min(th) + 1;
key = round([tr.lat tr.lon] * 1e5);              % ~1 m resolution
[ukey, ~, g] = unique(key, 'rows');
cnt = accumarray(g, 1);
isSite = false(size(ukey, 1), 1);
for c = find(cnt > 200 & cnt >= opts.static_min_frac * max(cnt))'
    idx = (g == c);
    if numel(unique(th(idx))) / nHours >= opts.static_cover && ...
            median(tr.spd(idx)) < opts.static_max_spd
        isSite(c) = true;
    end
end
siteKeys = find(isSite);
isStaticRow = isSite(g);
info.n_static_rows = sum(isStaticRow); info.n_mobile_rows = sum(~isStaticRow);

%% 4. SIGNAL PROCESSING: BIN EACH STATIC SITE ------------------------------
% 10-min bin means per site. Averaging ~200 samples per bin cuts the
% injected noise by ~sqrt(200) = 14x (1-sigma noise ~27 ug/m3 per sample ->
% ~1.9 per site-bin), which is why the noise test barely moves the score.
bd = opts.bin_min / 1440;
b0 = floor(min(tr.t) / bd); nb = floor(max(tr.t) / bd) - b0 + 1;
nS = numel(siteKeys);
S = nan(nb, nS); N = zeros(nb, nS); lat = zeros(1, nS); lon = lat;
for j = 1:nS
    idx = (g == siteKeys(j));
    b = floor(tr.t(idx) / bd) - b0 + 1;
    N(:, j) = accumarray(b, 1, [nb 1]);
    S(:, j) = accumarray(b, tr.pm(idx), [nb 1]) ./ N(:, j);
    lat(j) = ukey(siteKeys(j), 1) / 1e5; lon(j) = ukey(siteKeys(j), 2) / 1e5;
end
S(N == 0) = NaN;

%% 5. DROP FAULTY STATIC SITES ---------------------------------------------
% A site that does not move with the others is broken or unrepresentative
% (Tianjin static #6: corr 0.54 with the rest, reads ~7.6 where passing
% mobile sensors read ~36). Foshan sites correlate 0.93-0.98, so 0.7 keeps
% all of them.
keep = true(1, nS);
if nS >= 3
    for j = 1:nS
        oth = pm_short_term__medn(S(:, setdiff(1:nS, j)), 2);
        v = isfinite(oth) & isfinite(S(:, j));
        if sum(v) > 10 && pm_short_term__corr_simple(S(v, j), oth(v)) < opts.min_site_corr
            keep(j) = false;
        end
    end
end
if ~any(keep), keep(:) = true; end
info.dropped_sites = sum(~keep);
S = S(:, keep); N = N(:, keep); lat = lat(keep); lon = lon(keep);
siteKeys = siteKeys(keep); nS = numel(siteKeys);
info.n_sites = nS;

%% 6. TRAIN: CITY LEVEL + SITE OFFSETS -------------------------------------
% Alternate L(t) = mean_s(S - o_s) and o_s = mean_t(S - L) so that bins
% where some sites are missing do not shift the level. Offsets are
% centred (sum to 0). These offsets are the "trained" parameters of the
% model: estimated from the 3-day training window.
o = zeros(1, nS);
for it = 1:3
    L = mean(S - o, 2, 'omitnan');
    o = mean(S - L, 1, 'omitnan'); o = o - mean(o);
end
info.site_offsets = o; info.site_latlon = [lat(:) lon(:)];

%% 7. PREDICT ---------------------------------------------------------------
pred = nan(numel(te.t), 1); pred_sd = pred;
[level, tRef, src] = pm_short_term__current_level(tr, g, siteKeys, o, isStaticRow, L, opts);
info.level = level; info.level_source = src;

% uncertainty of the level: RMS change of the 10-min city level over the
% same horizon in the training window (empirical persistence error).
% L stays on its regular 10-min grid WITH its NaN bins, so that a lag of k
% bins always means k*10 minutes of real time (dropping empty bins first
% would join the two sides of a gap and mis-state the horizon).
Lv = L;

[locs, ~, locId] = unique(round([te.lat te.lon] * 1e5) / 1e5, 'rows');
for k = 1:size(locs, 1)
    rows = (locId == k);
    % 7a. offset at the test site: inverse-distance weighting (power 2,
    %     minimum distance 0.2 km) of the sites' offsets. Validated: removing
    %     it raises test-half NRMSE from 0.2038 to 0.2102 (noise 0). (Calibrated mobile passes near the site were
    %     tried as well and were worse: the static offsets are mostly sensor
    %     calibration, which vehicles driving past do not see.)
    if nS > 0
        d = pm_short_term__haversine_km(locs(k, 1), locs(k, 2), lat, lon);
        w = 1 ./ max(d, opts.idw_min_km) .^ opts.idw_power; w = w / sum(w);
        off = opts.offset_shrink * sum(w .* o);
        off_sd = std(o);
    else
        off = 0; off_sd = 0;
    end
    % 7b. forecast = level held flat (persistence) + offset
    pred(rows) = max(level + off, opts.min_pred);
    % 7c. uncertainty. The target is the MEAN over [t, t + 1 h), centred
    %     30 min after t, so the persistence error is measured at the middle
    %     of the target hour, not at t itself. (Using t understated the
    %     h = 1 sd: 4.1 vs an actual RMSE of 6.5; see st_uncertainty.m.)
    %     Label convention: in our validation a row stamped t is the mean of
    %     [t, t+1h); in the 11/16 competition files it is the mean of
    %     [t-1h, t) (checked: the test humidity equals the hour BEFORE the
    %     stamp). Detect it: if the first stamp is ~1 h after the end of the
    %     training data, the stamps mark hour ends.
    lead = (min(te.t(rows)) - tRef) * 24;
    if lead > 0.75, mid = -0.5; else, mid = 0.5; end
    hz = max((te.t(rows) - tRef) * 24 + mid, 0.1);  % hours to mid-target
    pred_sd(rows) = sqrt(pm_short_term__persist_sd(Lv, opts.bin_min, hz).^2 + off_sd^2);
end

% last-resort fallback: never return NaN to the grader
bad = ~isfinite(pred);
pred(bad) = mean(tr.pm); pred_sd(bad) = std(tr.pm);
end

%% ===================== LEVEL AT THE FORECAST ORIGIN =====================
function [level, tRef, src] = pm_short_term__current_level(tr, g, siteKeys, o, isStaticRow, L, opts)
% Exponentially weighted mean (EWMA) of EVERY raw static sample of the last
% 3 h, offset-corrected per site:  w = exp(-age / tau).
%   * tau trades noise against lag. It is chosen on the development half
%     of st_validate.m (mean NRMSE over noise 0 / 0.5 / 1.0 sigma):
%       tau 2: 0.1472   tau 5: 0.1479   tau 10: 0.1511   tau 20: 0.1558
%     On ONE sensor the optimum is ~10 min (single-sensor study); pooling 4
%     sites gives 4x the samples, so a shorter, faster-reacting tau wins.
%   * Removing the smoothing entirely (latest sample of each site) is as
%     good without noise but much worse with it: test-half NRMSE 0.2028 /
%     0.2393 / 0.3195 vs 0.2038 / 0.2052 / 0.2073.
%   * Damping the level toward the 24-h mean (AR(1)) was worse (0.1914).
% Static data must be RECENT to count as "now": if the newest static
% sample is older than max_stale_min, a few stale samples would otherwise
% get all the weight and an hours-old level would be used as current
% (found by the missing-data check in st_validate.m).
tRef = max(tr.t);
lastStatic = max([tr.t(isStaticRow); -Inf]);
fresh = (tRef - lastStatic) * 1440 <= opts.max_stale_min;
if fresh
    [level, ok] = pm_short_term__static_ewma(tr, g, siteKeys, o, tRef, opts);
    if ok, src = 'static EWMA'; return, end
end
% FALLBACK 1: no static data in the last 3 h -> calibrated mobile data.
% Mobile sensors read differently from static ones (Foshan: ~+10), so
% their readings are shifted by the median mobile-minus-level difference
% over the training window before smoothing.
mob = ~isStaticRow & tr.t >= tRef - 3/24;
if any(mob) && any(isfinite(L))
    bd = opts.bin_min / 1440;
    allMob = ~isStaticRow;
    b = floor(tr.t(allMob) / bd) - floor(min(tr.t) / bd) + 1;
    v = b <= numel(L) & b >= 1; b = b(v); pmM = tr.pm(allMob); pmM = pmM(v);
    bias = pm_short_term__medn(pmM - L(b));
    if ~isfinite(bias), bias = 0; end
    w = exp(-(tRef - tr.t(mob)) * 1440 / (3 * opts.tau_min));  % fewer samples -> longer tau
    level = sum(w .* (tr.pm(mob) - bias)) / sum(w); src = 'mobile EWMA (fallback)'; return
end
% FALLBACK 2: no recent mobile data either -> smooth the newest static data
% we do have (ages measured from the last static sample)
if isfinite(lastStatic)
    [level, ok] = pm_short_term__static_ewma(tr, g, siteKeys, o, lastStatic, opts);
    if ok, src = 'stale static EWMA (fallback)'; return, end
end
% FALLBACK 3: last known level, else the training mean
v = find(isfinite(L), 1, 'last');
if ~isempty(v), level = L(v); src = 'last level (fallback)';
else, level = mean(tr.pm); src = 'training mean (fallback)'; end
end

function [level, ok] = pm_short_term__static_ewma(tr, g, siteKeys, o, tRef, opts)
% opts.level_method = 'ewma' (default): exponentially weighted mean of the
% offset-corrected samples of the last 3 h.  'last' (ablation: smoothing
% removed): the single most recent offset-corrected sample of each site.
num = 0; den = 0;
for j = 1:numel(siteKeys)
    idx = (g == siteKeys(j)) & tr.t >= tRef - 3/24 & tr.t <= tRef;
    if ~any(idx), continue; end
    if strcmp(opts.level_method, 'last')
        tj = tr.t(idx); pj = tr.pm(idx); [~, k] = max(tj);
        num = num + (pj(k) - o(j)); den = den + 1;
        continue
    end
    w = exp(-(tRef - tr.t(idx)) * 1440 / opts.tau_min);
    num = num + sum(w .* (tr.pm(idx) - o(j)));   % offset-corrected samples
    den = den + sum(w);
end
ok = den > 0; level = num / max(den, eps);
end

%% ============================== DEFAULTS =================================
function o = pm_short_term__fill_defaults(o)
d.tau_min         = 2;     % EWMA time constant (minutes), chosen on the
                           % DEVELOPMENT half of the backtest (st_validate.m):
                           % mean dev NRMSE tau 2: .1472, 5: .1479, 10: .1511,
                           % 20: .1558. Not re-chosen on the test half.
d.level_method    = 'ewma';% 'ewma' | 'last' (ablation: no smoothing)
d.bin_min         = 10;    % bin size for offsets / site checks (minutes)
d.spike_k         = 12;    % spike threshold in robust sd
d.static_cover    = 0.5;   % static site: data in >= 50% of hours
d.static_max_spd  = 2;     % ... median speed below this
d.static_min_frac = 0.05;  % ... >= 5% of the busiest coordinate's samples
d.min_site_corr   = 0.7;   % drop sites that do not track the others
d.idw_power       = 2;     % inverse-distance weighting of offsets
d.idw_min_km      = 0.2;
d.offset_shrink   = 1;     % 0 = ignore offsets (ablation)
d.min_pred        = 1;     % PM2.5 sensors floor at 1
d.max_stale_min   = 30;    % static data older than this is not "now"
f = fieldnames(d);
for i = 1:numel(f), if ~isfield(o, f{i}), o.(f{i}) = d.(f{i}); end, end
end

%% ============================== HELPERS ==================================
function s = pm_short_term__parse_matrix(X, isTrain)
X = double(X);
t = X(:, 1); m = pm_short_term__medn(t);
if m > 1e11, t = t / 86400000 + 719529;          % POSIX ms
elseif m > 1e8, t = t / 86400 + 719529; end      % POSIX s  (else datenum)
s.t = t; s.hmd = X(:, 2);
c3 = X(:, 3); c4 = X(:, 4);
% speed has a much smaller median than temperature (static/parked ~0.3)
if pm_short_term__medn(c3) < pm_short_term__medn(c4), s.tmp = c4; s.spd = c3; else, s.tmp = c3; s.spd = c4; end
if isTrain, s.pm = X(:, 5); s.lat = X(:, 6); s.lon = X(:, 7);
else, s.lat = X(:, 5); s.lon = X(:, 6); end
end

function X = pm_short_term__table_to_matrix(X, isTrain)
% MATLAB table with variables time (datetime), hmd, spd, tmp, [pm2d5], lat,
% lon -> numeric matrix [datenum hmd tmp spd (pm2d5) lat lon]. Matrices pass
% through unchanged (columns 3/4 are detected later in pm_short_term__parse_matrix).
if ~isa(X, 'table'), return; end
t = X.time;
if isdatetime(t), t.TimeZone = ''; t = datenum(t); end
if isTrain
    X = [t, X.hmd, X.tmp, X.spd, X.pm2d5, X.lat, X.lon];
else
    X = [t, X.hmd, X.tmp, X.spd, X.lat, X.lon];
end
end

function s = pm_short_term__subset(s, ok)
f = fieldnames(s);
for i = 1:numel(f), s.(f{i}) = s.(f{i})(ok); end
end

function sd = pm_short_term__persist_sd(Lv, binMin, hz)
% empirical RMS of the level change over each horizon in the training data.
% Lv is on a regular time grid (NaN = empty bin); only pairs exactly `lag`
% bins apart with BOTH ends observed are used.
sd = zeros(size(hz));
for i = 1:numel(hz)
    lag = max(1, round(hz(i) * 60 / binMin));
    if lag < numel(Lv)
        d = Lv(1+lag:end) - Lv(1:end-lag); d = d(isfinite(d));
    else
        d = [];
    end
    if numel(d) >= 5, sd(i) = sqrt(mean(d.^2));
    else, v = Lv(isfinite(Lv)); sd(i) = std(v); end
end
end

function d = pm_short_term__haversine_km(lat1, lon1, lat2, lon2)
p = pi / 180;
a = sin((lat2 - lat1) * p / 2).^2 + cos(lat1 * p) .* cos(lat2 * p) .* sin((lon2 - lon1) * p / 2).^2;
d = 2 * 6371 * asin(min(1, sqrt(a)));
end

function r = pm_short_term__corr_simple(a, b)
a = a - mean(a); b = b - mean(b);
r = sum(a .* b) / sqrt(sum(a.^2) * sum(b.^2) + eps);
end

function m = pm_short_term__medn(x, dim)
% NaN-ignoring median (Octave's median has no 'omitnan')
if nargin < 2
    x = x(isfinite(x)); if isempty(x), m = NaN; else, m = median(x); end, return
end
if dim == 2, x = x.'; end
m = nan(1, size(x, 2));
for j = 1:size(x, 2)
    c = x(isfinite(x(:, j)), j); if ~isempty(c), m(j) = median(c); end
end
if dim == 2, m = m.'; end
end

% ===== from team_submission/pm_draft_level_model.m =====
function [pred_pm2d5, pred_std] = pm_draft_level_model(train_data, test_data, problem_type, opts)
%PM_DRAFT_LEVEL_MODEL  DRAFT long-term (2) and interpolation (3) model.
%
%   Placeholder used by pm_long_term.m / pm_interpolation.m until the
%   long-term and interpolation owners plug in their own models. It is the
%   earlier all-in-one model:  PM(site, t) = L(t) + o(site)
%     type 2: dew-point ridge regression of the city level + AR(1) residual
%     type 3: city level interpolated in time across the missing window
%   Known weakness: on the long-term validation split of the team's ridge
%   model (held-out static #5, 14-21 May) it scores NRMSE 0.717 vs 0.547 for
%   that model. Replace it.
%
%   train_data / test_data: MATLAB tables or the handout matrices.
%   Plain MATLAB, no toolboxes.

if nargin < 4 || isempty(opts), opts = struct(); end
train_data = pm_draft_level_model__table_to_matrix(train_data, true);
test_data  = pm_draft_level_model__table_to_matrix(test_data, false);
if problem_type == 1, error('pm_draft_level_model: problem_type 1 is handled by pm_short_term'); end

opts = pm_draft_level_model__fill_opts(opts, pm_draft_level_model__default_opts(problem_type));

% ---------- 1. parse and clean inputs ---------------------------------------
tr = pm_draft_level_model__parse_train(train_data);
te = pm_draft_level_model__parse_test(test_data);
tr = pm_draft_level_model__clean_train(tr, opts);

% ---------- 2. split static vs mobile, bin static sites --------------------
[site, isStaticRow] = pm_draft_level_model__find_static_sites(tr, opts);

M = numel(te.t);
pred_pm2d5 = nan(M, 1);
pred_std   = nan(M, 1);

% test locations (fixed sites); predict each separately
[locs, ~, locId] = unique(round([te.lat te.lon] * 1e5) / 1e5, 'rows');

for k = 1:size(locs, 1)
    rows = find(locId == k);
    tgt.lat = locs(k, 1); tgt.lon = locs(k, 2);
    tgt.t   = te.t(rows); tgt.hmd = te.hmd(rows); tgt.tmp = te.tmp(rows);

    off = pm_draft_level_model__site_offset_at(tgt, site, tr, isStaticRow, opts);

    switch problem_type
        case 1, [L, sL] = pm_draft_level_model__level_short(tgt, site, opts);
        case 2, [L, sL] = pm_draft_level_model__level_long(tgt, site, opts);
        case 3, [L, sL] = pm_draft_level_model__level_interp(tgt, site, opts);
        otherwise, error('problem_type must be 1, 2 or 3');
    end
    p = L + off.value;
    pred_pm2d5(rows) = max(p, opts.min_pred);
    pred_std(rows)   = sqrt(sL.^2 + off.sd.^2);
end

% last-resort fallback: never return NaN
bad = ~isfinite(pred_pm2d5);
if any(bad)
    pred_pm2d5(bad) = mean(tr.pm, 'omitnan');
    pred_std(bad) = std(tr.pm, 'omitnan');
end
end

% =============================================================================
% Options
% =============================================================================
function o = pm_draft_level_model__default_opts(problem_type)
o.min_pred        = 1;      % PM2.5 sensors floor at 1
o.spike_mad_k     = 12;     % remove PM > median + k*1.4826*MAD (gross spikes)
o.static_cover    = 0.5;    % a coordinate is "static" if it has data in >=50% of hours
o.static_max_spd  = 2;      % ...and its median speed is below this
o.static_min_frac = 0.05;   % ...and >= 5% of the busiest coordinate's samples (parked: <1%)
o.min_site_corr   = 0.7;    % drop static sites poorly correlated with the rest
o.idw_power       = 2;
o.idw_min_km      = 0.2;
o.offset_shrink   = 1.0;    % 0 = ignore local offsets, 1 = full IDW offset
o.use_mobile_offset = false;% use calibrated mobile data near the test site
o.mobile_radius_km  = 0.5;
o.mobile_min_hours  = 3;
switch problem_type
    case 1
        o.bin_min     = 10;   % static sites binned at 10 min
        o.level_method = 'ewma'; % 'ewma' (default) | 'bins'
        o.ewma_tau_min = 5;   % EWMA time constant (min). Leave-one-sensor-out
                              % backtest, NRMSE at noise 0 / 0.5 / 1.0 sigma:
                              % tau 5: .1856/.1862/.1873  tau 10: .1874/.1877/.1884
                              % tau 20: .1908/.1910/.1913  10-min bin: .1873/.1879/.1888
                              % (pooling 4 sites -> 4x samples, so a shorter tau
                              % than the single-sensor optimum of 10 min wins)
        o.persist_bins = 1;   % 'bins': persistence of the last 10 min...
        o.min_samples = 1000; % ...or longer, until >= this many raw samples
        o.ar_damp     = false;% AR damping toward 24 h mean: hurt in backtest
    case 2
        o.bin_min     = 60;
        o.use_met     = true; % humidity regression
        o.use_tmp     = false;% separate temperature term: corr with PM unstable across weeks
        o.hum_feature = 'dewpt'; % 'rh' | 'dewpt' | 'both'. Dew point: 0.361 vs RH+T 0.371
        o.use_diurnal = false;% 24 h/12 h harmonics: hurt in backtest (0.413 vs 0.371)
        o.use_ar_resid = true;
        o.ridge       = 1e-3;
    case 3
        o.bin_min     = 5;
        o.interp_mode = 'idw_now';  % 'idw_now' | 'city_now' | 'time_interp' | 'blend'
        o.blend_w     = 0.5;
end
end

function o = pm_draft_level_model__fill_opts(o, d)
f = fieldnames(d);
for i = 1:numel(f)
    if ~isfield(o, f{i}), o.(f{i}) = d.(f{i}); end
end
end

% =============================================================================
% Parsing and cleaning
% =============================================================================
function tr = pm_draft_level_model__parse_train(X)
X = double(X);
tr.t   = pm_draft_level_model__to_days(X(:, 1));
c3 = X(:, 3); c4 = X(:, 4);
% Column order in the course text is [hmd tmp spd], but the provided tables
% are [hmd spd tmp]. Speed has a much smaller median (static/parked ~0.3).
if pm_draft_level_model__medn(c3) < pm_draft_level_model__medn(c4), tmp = c4; spd = c3; else, tmp = c3; spd = c4; end
tr.hmd = X(:, 2); tr.tmp = tmp; tr.spd = spd;
tr.pm  = X(:, 5); tr.lat = X(:, 6); tr.lon = X(:, 7);
end

function te = pm_draft_level_model__parse_test(X)
X = double(X);
te.t = pm_draft_level_model__to_days(X(:, 1));
c3 = X(:, 3); c4 = X(:, 4);
if pm_draft_level_model__medn(c3) < pm_draft_level_model__medn(c4), tmp = c4; spd = c3; else, tmp = c3; spd = c4; end
te.hmd = X(:, 2); te.tmp = tmp; te.spd = spd;
te.lat = X(:, 5); te.lon = X(:, 6);
end

function d = pm_draft_level_model__to_days(t)
% Accept MATLAB datenum (days), POSIX seconds or POSIX milliseconds.
m = pm_draft_level_model__medn(t);
if m > 1e11
    d = t / 86400000 + 719529;
elseif m > 1e8
    d = t / 86400 + 719529;
else
    d = t;
end
end

function tr = pm_draft_level_model__clean_train(tr, opts)
ok = isfinite(tr.t) & isfinite(tr.pm) & isfinite(tr.lat) & isfinite(tr.lon);
ok = ok & ~(tr.lat == 0 & tr.lon == 0);
% GPS glitches: far from the bulk of the data
mlat = median(tr.lat(ok)); mlon = median(tr.lon(ok));
ok = ok & abs(tr.lat - mlat) < 0.5 & abs(tr.lon - mlon) < 0.5;
% gross PM spikes only. NOTE: we deliberately do NOT clip negative values or
% apply asymmetric filters - the robustness test adds zero-mean Gaussian
% noise, and averaging unclipped values keeps the bin means unbiased.
p = tr.pm(ok);
med = median(p); s = 1.4826 * median(abs(p - med));
ok = ok & tr.pm <= med + opts.spike_mad_k * max(s, 1);
f = fieldnames(tr);
for i = 1:numel(f), tr.(f{i}) = tr.(f{i})(ok); end
end

% =============================================================================
% Static sites
% =============================================================================
function [site, isStaticRow] = pm_draft_level_model__find_static_sites(tr, opts)
th = floor(tr.t * 24);                      % absolute hour index
nHours = max(th) - min(th) + 1;
key = round([tr.lat tr.lon] * 1e5);
[ukey, ~, g] = unique(key, 'rows');
cnt = accumarray(g, 1);
% A real static sensor logs ~1200 samples/h at one exact coordinate. A parked
% vehicle's GPS jitters, spreading its samples over dozens of coordinates
% (Foshan mobile #2 at its depot: ~70 keys x ~300 samples, >50% hourly cover).
% So also require a sample count comparable to the busiest coordinate.
cand = find(cnt > 200 & cnt >= opts.static_min_frac * max(cnt));
isSite = false(size(ukey, 1), 1);
for c = cand'
    idx = (g == c);
    cover = numel(unique(th(idx))) / nHours;
    if cover >= opts.static_cover && median(tr.spd(idx)) < opts.static_max_spd
        isSite(c) = true;
    end
end
isStaticRow = isSite(g);
siteKeys = find(isSite);

% binning
binDays = opts.bin_min / 1440;
b0 = floor(min(tr.t) / binDays);
b1 = floor(max(tr.t) / binDays);
nb = b1 - b0 + 1;
S = nan(nb, numel(siteKeys)); H = S; T = S; N = zeros(nb, numel(siteKeys));
lat = zeros(1, numel(siteKeys)); lon = lat;
for j = 1:numel(siteKeys)
    idx = (g == siteKeys(j));
    b = floor(tr.t(idx) / binDays) - b0 + 1;
    n = accumarray(b, 1, [nb 1]);
    S(:, j) = accumarray(b, tr.pm(idx),  [nb 1]) ./ n;
    H(:, j) = accumarray(b, tr.hmd(idx), [nb 1]) ./ n;
    T(:, j) = accumarray(b, tr.tmp(idx), [nb 1]) ./ n;
    N(:, j) = n;
    lat(j) = ukey(siteKeys(j), 1) / 1e5; lon(j) = ukey(siteKeys(j), 2) / 1e5;
end
S(N == 0) = NaN; H(N == 0) = NaN; T(N == 0) = NaN;

% drop sites that do not move with the others (e.g. Tianjin static #6)
keep = true(1, size(S, 2));
if size(S, 2) >= 3
    for j = 1:size(S, 2)
        others = pm_draft_level_model__medn(S(:, setdiff(1:size(S, 2), j)), 2);
        v = isfinite(others) & isfinite(S(:, j));
        if sum(v) > 10
            r = pm_draft_level_model__corr_simple(S(v, j), others(v));
            if r < opts.min_site_corr, keep(j) = false; end
        end
    end
end
if ~any(keep), keep(:) = true; end
S = S(:, keep); H = H(:, keep); T = T(:, keep); N = N(:, keep);
lat = lat(keep); lon = lon(keep);

% raw samples of the last 3 h per kept site (for the short-term EWMA level)
kk = siteKeys(keep); tEnd = max(tr.t(isStaticRow));
site.rt = cell(1, numel(kk)); site.rp = site.rt;
for j = 1:numel(kk)
    idx = (g == kk(j)) & tr.t >= tEnd - 3/24;
    site.rt{j} = tr.t(idx); site.rp{j} = tr.pm(idx);
end
site.tEnd = tEnd;

% decompose S = city level + site offset (2 sweeps handle missing sites)
o = zeros(1, size(S, 2));
for it = 1:3
    L = mean(S - o, 2, 'omitnan');
    o = mean(S - L, 1, 'omitnan');
    o = o - mean(o);
end

site.S = S; site.H = H; site.T = T; site.N = N;
site.lat = lat; site.lon = lon; site.offset = o;
site.L = L;                                   % city level per bin
site.Hc = mean(H, 2, 'omitnan'); site.Tc = mean(T, 2, 'omitnan');
site.tb = ((b0:b1)' + 0.5) * binDays;          % bin centre times (days)
site.binDays = binDays;
site.dropped = sum(~keep);
end

function r = pm_draft_level_model__corr_simple(a, b)
a = a - mean(a); b = b - mean(b);
r = sum(a .* b) / sqrt(sum(a .^ 2) * sum(b .^ 2) + eps);
end

function w = pm_draft_level_model__idw_weights(lat0, lon0, lat, lon, opts)
d = pm_draft_level_model__haversine_km(lat0, lon0, lat, lon);
w = 1 ./ max(d, opts.idw_min_km) .^ opts.idw_power;
w = w / sum(w);
end

function d = pm_draft_level_model__haversine_km(lat1, lon1, lat2, lon2)
p = pi / 180;
a = sin((lat2 - lat1) * p / 2) .^ 2 + cos(lat1 * p) .* cos(lat2 * p) .* sin((lon2 - lon1) * p / 2) .^ 2;
d = 2 * 6371 * asin(min(1, sqrt(a)));
end

% =============================================================================
% Local offset at the test location
% =============================================================================
function off = pm_draft_level_model__site_offset_at(tgt, site, tr, isStaticRow, opts)
w = pm_draft_level_model__idw_weights(tgt.lat, tgt.lon, site.lat, site.lon, opts);
o_idw = sum(w .* site.offset);
off.value = opts.offset_shrink * o_idw;
off.sd = std(site.offset);                    % spread of offsets = uncertainty
if isnan(off.sd), off.sd = 0; end

if opts.use_mobile_offset
    mob = ~isStaticRow;
    if any(mob)
        d = pm_draft_level_model__haversine_km(tgt.lat, tgt.lon, tr.lat(mob), tr.lon(mob));
        near = d < opts.mobile_radius_km;
        if any(near)
            tm = tr.t(mob); pm = tr.pm(mob);
            % calibrate mobile -> static by binwise ratio of medians
            b  = floor(tm / site.binDays);
            bs = floor(site.tb / site.binDays);
            [ub, ~, gb] = unique(b);
            medAll = accumarray(gb, pm, [], @median);
            [tf, loc] = ismember(ub, bs);
            Lb = nan(size(ub)); Lb(tf) = site.L(loc(tf));
            v = isfinite(Lb) & medAll > 0;
            ratio = median(Lb(v) ./ medAll(v));
            % local anomaly near target, per bin
            bn = b(near); [ubn, ~, gn] = unique(bn);
            mn = accumarray(gn, pm(near), [], @median) * ratio;
            [tf, loc] = ismember(ubn, bs);
            an = mn(tf) - site.L(loc(tf));
            an = an(isfinite(an));
            if numel(an) >= opts.mobile_min_hours * (60 / opts.bin_min)
                % precision-weighted blend of static-IDW and mobile estimates
                s2m = var(an) / numel(an) + (0.3 * std(an))^2;
                s2s = off.sd^2 + eps;
                wm = s2s / (s2s + s2m);
                off.value = (1 - wm) * off.value + wm * median(an);
                off.sd = sqrt(1 / (1 / s2s + 1 / s2m));
            end
        end
    end
end
end

% =============================================================================
% Level models
% =============================================================================
function [L, sL] = pm_draft_level_model__level_short(tgt, site, opts)
Lc = site.L; v = find(isfinite(Lc));
if strcmp(opts.level_method, 'ewma')
    % exponentially weighted mean of every raw static sample of the last 3 h,
    % offset-corrected per site: w = exp(-age / tau). Pools all sites, so the
    % effective sample count is high and the injected noise averages out.
    num = 0; den = 0;
    for j = 1:numel(site.rt)
        if isempty(site.rt{j}), continue; end
        w = exp(-(site.tEnd - site.rt{j}) * 1440 / opts.ewma_tau_min);
        num = num + sum(w .* (site.rp{j} - site.offset(j))); den = den + sum(w);
    end
    if den > 0
        last = num / den;
        hz = max(tgt.t - site.tEnd, 0) * 24;
        L = repmat(last, size(tgt.t));
        sL = pm_draft_level_model__persistence_sd(Lc(v), opts.bin_min, hz);
        return
    end                                        % no recent data: fall back to bins
end
% Sample-weighted level over the most recent bins: take at least
% persist_bins bins and keep going back until min_samples raw samples are
% covered. A single sparse bin at a data edge is otherwise very noise-prone.
A = site.S - site.offset; Nw = site.N; Nw(~isfinite(A)) = 0; A(~isfinite(A)) = 0;
num = 0; den = 0; nb = 0;
for b = v(end):-1:1
    num = num + sum(Nw(b, :) .* A(b, :)); den = den + sum(Nw(b, :)); nb = nb + 1;
    if nb >= opts.persist_bins && den >= opts.min_samples, break; end
end
last = num / max(den, 1);
tLast = site.tb(v(end));
hz = max(tgt.t - tLast, 0) * 24;               % horizon in hours
if opts.ar_damp
    % hourly AR(1) on the level, damp toward the last-24h mean
    [phi, mu] = pm_draft_level_model__ar1_fit(Lc(v), round(60 / opts.bin_min), 24 * 60 / opts.bin_min);
    L = mu + phi .^ hz .* (last - mu);
else
    L = repmat(last, size(tgt.t));
end
% uncertainty: empirical persistence error growth in training
sL = pm_draft_level_model__persistence_sd(Lc(v), opts.bin_min, hz);
end

function [L, sL] = pm_draft_level_model__level_long(tgt, site, opts)
y = site.L; Hc = site.Hc; Tc = site.Tc; tb = site.tb;
v = isfinite(y) & isfinite(Hc) & isfinite(Tc);
Xtr = pm_draft_level_model__design(tb(v), Hc(v), Tc(v), opts);
ytr = y(v);
% standardize columns (except intercept) for ridge
mu = mean(Xtr(:, 2:end), 1); sd = std(Xtr(:, 2:end), 0, 1); sd(sd == 0) = 1;
Z = [ones(sum(v), 1), (Xtr(:, 2:end) - mu) ./ sd];
R = opts.ridge * eye(size(Z, 2)); R(1, 1) = 0;
beta = (Z' * Z + size(Z, 1) * R) \ (Z' * ytr);

% future met at the test site; fill gaps with the training diurnal mean
hf = tgt.hmd; tf = tgt.tmp;
hf(~isfinite(hf)) = mean(Hc(v));
tf(~isfinite(tf)) = mean(Tc(v));
Xf = pm_draft_level_model__design(tgt.t, hf, tf, opts);
% Never extrapolate the met features: the static enclosures' temperature can
% be almost constant during training (tiny std -> huge coefficient), while the
% test site's sensor varies. Clip each feature to its training range.
lo = min(Xtr, [], 1); hi = max(Xtr, [], 1);
Xf = min(max(Xf, lo), hi);
Zf = [ones(numel(tgt.t), 1), (Xf(:, 2:end) - mu) ./ sd];
L = Zf * beta;

res = ytr - Z * beta;
hz = max(tgt.t - tb(find(v, 1, 'last')), 0) * 24;
if opts.use_ar_resid && numel(res) > 5
    phi = max(0, min(1, sum(res(1:end-1) .* res(2:end)) / sum(res(1:end-1) .^ 2)));
    L = L + phi .^ hz .* res(end);
    sL = std(res) * sqrt(1 - phi .^ (2 * hz));
else
    sL = repmat(std(res), size(hz));
end
L = min(max(L, min(ytr)), max(ytr));          % stay inside the observed range
end

function X = pm_draft_level_model__design(t, h, tm, opts)
X = ones(numel(t), 1);
if opts.use_met
    switch opts.hum_feature
        case 'rh',     X = [X, h(:)];
        case 'dewpt',  X = [X, pm_draft_level_model__dewpoint(tm(:), h(:))];
        case 'both',   X = [X, h(:), pm_draft_level_model__dewpoint(tm(:), h(:))];
    end
end
if opts.use_met && opts.use_tmp, X = [X, tm(:)]; end
if opts.use_diurnal
    w = 2 * pi * mod(t(:), 1);                 % fraction of day
    X = [X, sin(w), cos(w), sin(2 * w), cos(2 * w)];
end
end

function [L, sL] = pm_draft_level_model__level_interp(tgt, site, opts)
tb = site.tb; binDays = site.binDays;
bt = floor(tgt.t / binDays);
bs = floor(tb / binDays);
[tf, loc] = ismember(bt, bs);
Lc = site.L;
% temporal interpolation of the level across the gap
v = isfinite(Lc);
Lint = interp1(tb(v), Lc(v), (bt + 0.5) * binDays, 'linear', 'extrap');

Lnow = nan(size(tgt.t)); Inow = Lnow;
w = pm_draft_level_model__idw_weights(tgt.lat, tgt.lon, site.lat, site.lon, opts);
for i = 1:numel(tgt.t)
    if tf(i)
        Lnow(i) = Lc(loc(i));
        s = site.S(loc(i), :); m = isfinite(s);
        if any(m), Inow(i) = sum(w(m) .* s(m)) / sum(w(m)); end
    end
end
off = opts.offset_shrink * sum(w .* site.offset);
switch opts.interp_mode
    case 'idw_now'
        % direct IDW of the simultaneous static readings (already local)
        L = Inow - off;                        % offset added back by caller
    case 'city_now'
        L = Lnow;
    case 'time_interp'
        L = Lint;
    case 'blend'
        L = opts.blend_w * (Inow - off) + (1 - opts.blend_w) * Lint;
end
miss = ~isfinite(L);
L(miss) = Lint(miss);                          % window blanked for every sensor
sL = repmat(std(site.offset), size(L));
sL(miss) = sL(miss) * 2;
end

% =============================================================================
% Small time-series helpers
% =============================================================================
function [phi, mu] = pm_draft_level_model__ar1_fit(x, lag, muWin)
x = x(:);
mu = mean(x(max(1, end - muWin + 1):end));
a = x(1:end-lag) - mu; b = x(1+lag:end) - mu;
phi = max(0, min(1, sum(a .* b) / sum(a .^ 2)));   % per "lag" bins = per hour
end

function s = pm_draft_level_model__persistence_sd(x, binMin, hz)
x = x(:); s = zeros(size(hz));
for i = 1:numel(hz)
    lag = max(1, round(hz(i) * 60 / binMin));
    if lag < numel(x)
        e = x(1+lag:end) - x(1:end-lag);
        s(i) = sqrt(mean(e .^ 2));
    else
        s(i) = std(x);
    end
end
end

function m = pm_draft_level_model__medn(x, dim)
% NaN-ignoring median (Octave's median has no 'omitnan').
if nargin < 2
    x = x(isfinite(x)); if isempty(x), m = NaN; else, m = median(x); end
    return
end
if dim == 2, x = x.'; end
m = nan(1, size(x, 2));
for j = 1:size(x, 2)
    c = x(isfinite(x(:, j)), j); if ~isempty(c), m(j) = median(c); end
end
if dim == 2, m = m.'; end
end

function td = pm_draft_level_model__dewpoint(T, RH)
% Magnus formula, deg C. Dew point tracks absolute moisture, which in the
% Tianjin data correlates with PM2.5 more strongly than relative humidity.
a = 17.62; b = 243.12;
g = log(min(max(RH, 1), 100) / 100) + a * T ./ (b + T);
td = b * g ./ (a - g);
end

function X = pm_draft_level_model__table_to_matrix(X, isTrain)
% table [time hmd spd tmp (pm2d5) lat lon] -> [datenum hmd tmp spd (pm2d5) lat lon]
if ~isa(X, 'table'), return; end
t = X.time;
if isdatetime(t), t.TimeZone = ''; t = datenum(t); end
if isTrain, X = [t, X.hmd, X.tmp, X.spd, X.pm2d5, X.lat, X.lon];
else,       X = [t, X.hmd, X.tmp, X.spd, X.lat, X.lon]; end
end

